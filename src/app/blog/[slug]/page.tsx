export function generateStaticParams() {
  return posts.map((post) => ({ slug: post.slug }));
}

export function generateMetadata({ params }: { params: { slug: string } }) {
  const post = posts.find((p) => p.slug === params.slug);
  if (!post) return { title: 'Not Found' };
  return {
    title: `${post.title} | Retire Without Selling`,
    description: post.content.substring(0, 160),
  };
}

export default function BlogPost({ params }: { params: { slug: string } }) {
  const post = posts.find((p) => p.slug === params.slug);
  if (!post) return notFound();

  return (
    <div className="max-w-4xl mx-auto px-6 py-24">
      <div className="mb-8">
        <span className="text-[#3A7BFF] text-sm font-semibold uppercase tracking-wider">{post.category}</span>
        <span className="text-[#94a3b8] text-sm ml-4">{post.date}</span>
      </div>
      <h1 className="text-4xl md:text-5xl mb-12 leading-tight">{post.title}</h1>
      <div className="prose prose-invert prose-lg max-w-none">
        {post.content.split('\n\n').map((paragraph, index) => {
          if (paragraph.startsWith('The ') && paragraph.endsWith(':') && paragraph.split(' ').length < 8) {
            return <h2 key={index} className="text-2xl text-white mt-12 mb-6">{paragraph}</h2>;
          }
          if (paragraph.startsWith('- ')) {
            return (
              <ul key={index} className="list-disc list-inside text-[#94a3b8] space-y-2 my-6">
                {paragraph.split('\n').map((item, i) => (
                  <li key={i}>{item.replace('- ', '')}</li>
                ))}
              </ul>
            );
          }
          return <p key={index} className="text-[#94a3b8] leading-relaxed mb-6">{paragraph}</p>;
        })}
      </div>
      <div className="mt-16 pt-8 border-t border-[#1e293b]">
        <Link href="/blog" className="text-[#3A7BFF] font-semibold hover:text-white transition-colors">
          ← Back to all articles
        </Link>
      </div>
    </div>
  );
}
